export function getMapByName(name: string): MapDef | undefined {
  const id = name.toLowerCase().replace(/\s+/g, "");
  return MAPS.get(id);
}

export function listMaps(): MapDef[] {
  return [...MAPS.values()].sort((a, b) => a.rows - b.rows || a.name.localeCompare(b.name));
}
