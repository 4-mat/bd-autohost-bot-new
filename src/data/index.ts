export interface AbilityData {
  name: string;
  level: number;
  frequency: string;
  mr: number;
  roll: string;
  damageType: "Physical" | "Magical" | "";
  actionType:
    | "Standard"
    | "Full"
    | "Movement"
    | "Swift"
    | "Free"
    | "Trigger"
    | "Reaction"
    | "Passive"
    | "";
  targetAmount: number | "AoE";
  targetGroup: string;
  range: string;
  effect: string;
  maxUses?: number;
}

export interface ClassData {
  name: string;
  stats: {
    hp: string;
    atk: string;
    mag: string;
    pd: string;
    md: string;
    eva: string;
    mp: string;
  };
  abilities: AbilityData[];
  description: string;
}

export interface WeaponData {
  name: string;
  branch: string;
  stats: {
    hp: string;
    atk: string;
    mag: string;
    pd: string;
    md: string;
    eva: string;
    mp: string;
  };
  abilities: AbilityData[];
  description: string;
}

